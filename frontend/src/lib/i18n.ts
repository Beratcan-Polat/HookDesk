const resources = Object.fromEntries(
  (['en', 'tr'] as const).map((language, index) => [
    language,
    {
      translation: Object.fromEntries(
        Object.entries(phrases).map(([key, value]) => [key, value[index]]),
      ),
    },
  ]),
)
const initial =
  localStorage.getItem('hookdesk.locale') || (navigator.language.startsWith('tr') ? 'tr' : 'en')
void i18n
  .use(initReactI18next)
  .init({ resources, lng: initial, fallbackLng: 'en', interpolation: { escapeValue: false } })
i18n.on('languageChanged', (language) => {
  localStorage.setItem('hookdesk.locale', language)
  document.documentElement.lang = language
})
export default i18n
